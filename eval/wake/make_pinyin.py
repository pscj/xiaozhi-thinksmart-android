"""Write thinksmart_client/pinyin.txt: toneless pinyin of the 6763 GB2312 characters, one syllable per line.

wake_verify.py compares recognised text with the wake words by sound, without shipping pypinyin
(its phrase dictionary costs tens of MB of memory on the device).

    uv run --no-project --with pypinyin python eval/wake/make_pinyin.py
"""
import collections
import pathlib
import sys

from pypinyin import Style, lazy_pinyin

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from common import CLIENT  # noqa: E402

by_syllable = collections.defaultdict(list)
for hi in range(0xB0, 0xF8):
    for lo in range(0xA1, 0xFF):
        try:
            ch = bytes([hi, lo]).decode('gb2312')
        except UnicodeDecodeError:
            continue
        py = lazy_pinyin(ch, style=Style.NORMAL, errors='ignore')
        if py and py[0].isascii():
            by_syllable[py[0].replace('ü', 'v')].append(ch)
lines = [f'{s}\t{"".join(chs)}' for s, chs in sorted(by_syllable.items())]
out = CLIENT / 'thinksmart_client' / 'pinyin.txt'
out.write_text('# generated by eval/wake/make_pinyin.py (pypinyin, GB2312 characters, most common reading)\n'
               + '\n'.join(lines) + '\n')
print(sum(len(c) for c in by_syllable.values()), 'characters,', len(lines), 'syllables ->', out)
